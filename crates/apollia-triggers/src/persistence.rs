//! SQLite persistence for triggers: `trigger_history` and `trigger_state`.
//!
//! [`TriggerPersistence`] is a **synchronous** struct (no Tokio actor). It is
//! meant to be used directly from [`crate::engine::TriggerEngine`] (the SQLite
//! connection is `Send`, so it lives in the actor's Tokio task) or via
//! `spawn_blocking` when called from a context that cannot tolerate blocking.
//!
//! The [`include_str`] migration is idempotent (`CREATE TABLE IF NOT EXISTS`).

use std::collections::HashMap;

use chrono::{DateTime, Utc};
use rusqlite::{params, Connection};

// --- Errors ----------------------------------------------------------------

/// Trigger persistence errors.
#[derive(thiserror::Error, Debug)]
pub enum TriggerPersistenceError {
    /// Underlying SQLite error.
    #[error("database error: {0}")]
    Database(#[from] rusqlite::Error),

    /// Failed to parse a timestamp stored in the database.
    #[error("timestamp parse error: {0}")]
    TimestampParse(String),
}

// --- Result types ------------------------------------------------------------

/// History entry returned by [`TriggerPersistence::query_history`].
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct TriggerHistoryEntry {
    /// Unique entry identifier (hex randomblob generated by SQLite).
    pub id: String,
    /// Identifier of the relevant trigger.
    pub trigger_id: String,
    /// Target agent name.
    pub agent_name: String,
    /// Fire timestamp.
    pub fired_at: DateTime<Utc>,
    /// Identifier of the submitted task; `None` when `status` is `skipped` or `error`.
    pub task_id: Option<String>,
    /// Status: `"fired"` | `"skipped"` | `"error"`.
    pub status: String,
    /// Reason for the skip or error; `None` when `status` is `"fired"`.
    pub reason: Option<String>,
    /// Full trigger JSON payload; `None` when absent (timer without payload).
    pub payload_json: Option<String>,
    /// Dispatch time in milliseconds (trigger reception to task submission).
    pub dispatch_ms: Option<i64>,
}

/// Current state of a trigger in `trigger_state`.
#[derive(Debug, Clone)]
pub struct TriggerStateRow {
    /// Trigger identifier.
    pub trigger_id: String,
    /// Timestamp of the last successful fire; `None` if never fired.
    pub last_fired: Option<DateTime<Utc>>,
    /// Cumulative count of successful fires.
    pub fire_count: u64,
    /// Cumulative count of skips.
    pub skip_count: u64,
    /// Whether the trigger is enabled in `trigger_state`.
    pub enabled: bool,
}

/// Trigger statistics recomputed from the `trigger_history` table.
#[derive(Debug, Clone)]
pub struct TriggerStats {
    /// Count of successful fires.
    pub fire_count: u64,
    /// Count of skips.
    pub skip_count: u64,
    /// Timestamp of the last successful fire; `None` if never fired.
    pub last_fired: Option<DateTime<Utc>>,
}

// --- Helpers -----------------------------------------------------------------

/// Adds columns to a table if they do not exist yet.
///
/// Uses `PRAGMA table_info` to list the existing columns, then runs
/// `ALTER TABLE ADD COLUMN` only for the missing ones.
fn add_columns_if_missing(
    conn: &Connection,
    table: &str,
    columns: &[(&str, &str)],
) -> Result<(), rusqlite::Error> {
    let mut stmt = conn.prepare(&format!("SELECT name FROM pragma_table_info('{table}')"))?;
    let existing: Vec<String> = stmt
        .query_map([], |row| row.get::<_, String>(0))?
        .collect::<rusqlite::Result<Vec<_>>>()?;

    for (col_name, col_type) in columns {
        if !existing.iter().any(|c| c == col_name) {
            conn.execute_batch(&format!(
                "ALTER TABLE {table} ADD COLUMN {col_name} {col_type};"
            ))?;
        }
    }
    Ok(())
}

/// Common context for recording a `trigger_history` entry: trigger identity,
/// target agent, timestamp, and optional JSON payload.
///
/// Groups the fields shared by [`TriggerPersistence::record_fired`],
/// [`TriggerPersistence::record_skipped`] and [`TriggerPersistence::record_error`].
pub struct TriggerRecord<'a> {
    /// Identifier of the relevant trigger.
    pub trigger_id: &'a str,
    /// Target agent name.
    pub agent_name: &'a str,
    /// Fire timestamp.
    pub fired_at: DateTime<Utc>,
    /// Full trigger JSON payload, `None` when absent (timer without payload).
    pub payload_json: Option<&'a str>,
}

// --- TriggerPersistence ------------------------------------------------------

/// Persistence interface for triggers, wrapping `rusqlite::Connection`.
///
/// Meant to be owned by [`crate::engine::TriggerEngine`]. The SQLite connection
/// implements `Send`, which allows storing it inside a `tokio::spawn`.
pub struct TriggerPersistence {
    conn: Connection,
}

impl TriggerPersistence {
    /// Opens (or creates) the SQLite database and applies the trigger tables migration.
    ///
    /// Uses `CREATE TABLE IF NOT EXISTS`, so it is idempotent. Fails fast: a
    /// migration error is fatal (`.expect`), in line with the runtime's
    /// fail-fast policy.
    pub fn open(db_path: &std::path::Path) -> Result<Self, TriggerPersistenceError> {
        let conn = Connection::open(db_path)?;
        // WAL for better concurrent write performance.
        conn.execute_batch("PRAGMA journal_mode=WAL;")?;
        conn.execute_batch(include_str!(
            "../../apollia-tools/migrations/003_trigger_tables.sql"
        ))?;
        // Add payload_json and dispatch_ms columns when missing, checking
        // existence via PRAGMA table_info.
        add_columns_if_missing(
            &conn,
            "trigger_history",
            &[("payload_json", "TEXT"), ("dispatch_ms", "INTEGER")],
        )?;
        Ok(Self { conn })
    }

    /// Persists a successful fire in `trigger_history` and increments `fire_count`.
    ///
    /// Also updates `trigger_state.last_fired` with `fired_at`.
    /// `payload_json` and `dispatch_ms` are optional for backward compatibility.
    pub fn record_fired(
        &mut self,
        record: TriggerRecord<'_>,
        task_id: &str,
        dispatch_ms: Option<i64>,
    ) -> Result<(), TriggerPersistenceError> {
        let fired_at_str = record.fired_at.to_rfc3339();
        self.conn.execute(
            "INSERT INTO trigger_history \
             (trigger_id, agent_name, fired_at, task_id, status, payload_json, dispatch_ms) \
             VALUES (?1, ?2, ?3, ?4, 'fired', ?5, ?6)",
            params![
                record.trigger_id,
                record.agent_name,
                fired_at_str,
                task_id,
                record.payload_json,
                dispatch_ms
            ],
        )?;
        self.conn.execute(
            "INSERT INTO trigger_state (trigger_id, last_fired, fire_count, skip_count) \
             VALUES (?1, ?2, 1, 0) \
             ON CONFLICT(trigger_id) DO UPDATE SET \
               last_fired = excluded.last_fired, \
               fire_count = fire_count + 1",
            params![record.trigger_id, fired_at_str],
        )?;
        Ok(())
    }

    /// Persists a skip (`on_busy=drop`) in `trigger_history` and increments `skip_count`.
    ///
    /// `payload_json` is optional and lets the payload be traced even on a skip.
    pub fn record_skipped(
        &mut self,
        record: TriggerRecord<'_>,
        reason: &str,
    ) -> Result<(), TriggerPersistenceError> {
        let fired_at_str = record.fired_at.to_rfc3339();
        self.conn.execute(
            "INSERT INTO trigger_history \
             (trigger_id, agent_name, fired_at, task_id, status, reason, payload_json) \
             VALUES (?1, ?2, ?3, NULL, 'skipped', ?4, ?5)",
            params![
                record.trigger_id,
                record.agent_name,
                fired_at_str,
                reason,
                record.payload_json
            ],
        )?;
        self.conn.execute(
            "INSERT INTO trigger_state (trigger_id, fire_count, skip_count) \
             VALUES (?1, 0, 1) \
             ON CONFLICT(trigger_id) DO UPDATE SET \
               skip_count = skip_count + 1",
            params![record.trigger_id],
        )?;
        Ok(())
    }

    /// Persists a `TaskRouter` submission error in `trigger_history`.
    ///
    /// `payload_json` is optional and lets the payload be traced even on an error.
    pub fn record_error(
        &mut self,
        record: TriggerRecord<'_>,
        error: &str,
    ) -> Result<(), TriggerPersistenceError> {
        let fired_at_str = record.fired_at.to_rfc3339();
        self.conn.execute(
            "INSERT INTO trigger_history \
             (trigger_id, agent_name, fired_at, task_id, status, reason, payload_json) \
             VALUES (?1, ?2, ?3, NULL, 'error', ?4, ?5)",
            params![
                record.trigger_id,
                record.agent_name,
                fired_at_str,
                error,
                record.payload_json
            ],
        )?;
        Ok(())
    }

    /// Returns the last `limit` entries for a given trigger, sorted `fired_at DESC`.
    pub fn query_history(
        &self,
        trigger_id: &str,
        limit: usize,
    ) -> Result<Vec<TriggerHistoryEntry>, TriggerPersistenceError> {
        let mut stmt = self.conn.prepare(
            "SELECT id, trigger_id, agent_name, fired_at, task_id, status, reason, \
                    payload_json, dispatch_ms \
             FROM trigger_history \
             WHERE trigger_id = ?1 \
             ORDER BY fired_at DESC \
             LIMIT ?2",
        )?;

        let mut entries = Vec::new();
        let rows = stmt.query_map(params![trigger_id, limit as i64], |row| {
            Ok(RawHistoryRow {
                id: row.get(0)?,
                trigger_id: row.get(1)?,
                agent_name: row.get(2)?,
                fired_at: row.get(3)?,
                task_id: row.get(4)?,
                status: row.get(5)?,
                reason: row.get(6)?,
                payload_json: row.get(7)?,
                dispatch_ms: row.get(8)?,
            })
        })?;

        for row_result in rows {
            let row = row_result?;
            let fired_at = DateTime::parse_from_rfc3339(&row.fired_at)
                .map(|dt| dt.with_timezone(&Utc))
                .map_err(|e| TriggerPersistenceError::TimestampParse(e.to_string()))?;
            entries.push(TriggerHistoryEntry {
                id: row.id,
                trigger_id: row.trigger_id,
                agent_name: row.agent_name,
                fired_at,
                task_id: row.task_id,
                status: row.status,
                reason: row.reason,
                payload_json: row.payload_json,
                dispatch_ms: row.dispatch_ms,
            });
        }
        Ok(entries)
    }

    /// Recomputes the counters of all triggers from `trigger_history`.
    ///
    /// Returns a `trigger_id -> TriggerStats` map. Triggers with no history do
    /// not appear in the map; their counters stay at zero on the engine side.
    /// The query uses `SUM(CASE WHEN ...)` for maximum compatibility with every
    /// SQLite version bundled in rusqlite.
    pub fn load_counters(&self) -> Result<HashMap<String, TriggerStats>, TriggerPersistenceError> {
        let mut stmt = self.conn.prepare(
            "SELECT trigger_id, \
                    SUM(CASE WHEN status = 'fired'   THEN 1 ELSE 0 END) AS fire_count, \
                    SUM(CASE WHEN status = 'skipped' THEN 1 ELSE 0 END) AS skip_count, \
                    MAX(CASE WHEN status = 'fired'   THEN fired_at ELSE NULL END) AS last_fired \
             FROM trigger_history \
             GROUP BY trigger_id",
        )?;

        let mut map = HashMap::new();
        let rows = stmt.query_map([], |row| {
            Ok(RawCounterRow {
                trigger_id: row.get(0)?,
                fire_count: row.get::<_, i64>(1)?,
                skip_count: row.get::<_, i64>(2)?,
                last_fired: row.get(3)?,
            })
        })?;

        for row_result in rows {
            let row = row_result?;
            let last_fired = row
                .last_fired
                .map(|s: String| {
                    DateTime::parse_from_rfc3339(&s)
                        .map(|dt| dt.with_timezone(&Utc))
                        .map_err(|e| TriggerPersistenceError::TimestampParse(e.to_string()))
                })
                .transpose()?;
            map.insert(
                row.trigger_id,
                TriggerStats {
                    fire_count: row.fire_count as u64,
                    skip_count: row.skip_count as u64,
                    last_fired,
                },
            );
        }

        Ok(map)
    }

    /// Returns the current state of a trigger (`last_fired`, `fire_count`, `skip_count`).
    ///
    /// Returns `None` if no state exists yet for this trigger.
    pub fn get_state(
        &self,
        trigger_id: &str,
    ) -> Result<Option<TriggerStateRow>, TriggerPersistenceError> {
        let mut stmt = self.conn.prepare(
            "SELECT trigger_id, last_fired, fire_count, skip_count, enabled \
             FROM trigger_state \
             WHERE trigger_id = ?1",
        )?;

        let mut rows = stmt.query_map(params![trigger_id], |row| {
            Ok(RawStateRow {
                trigger_id: row.get(0)?,
                last_fired: row.get(1)?,
                fire_count: row.get::<_, i64>(2)?,
                skip_count: row.get::<_, i64>(3)?,
                enabled: row.get(4)?,
            })
        })?;

        match rows.next() {
            None => Ok(None),
            Some(row_result) => {
                let row = row_result?;
                let last_fired = row
                    .last_fired
                    .map(|s: String| {
                        DateTime::parse_from_rfc3339(&s)
                            .map(|dt| dt.with_timezone(&Utc))
                            .map_err(|e| TriggerPersistenceError::TimestampParse(e.to_string()))
                    })
                    .transpose()?;
                Ok(Some(TriggerStateRow {
                    trigger_id: row.trigger_id,
                    last_fired,
                    fire_count: row.fire_count as u64,
                    skip_count: row.skip_count as u64,
                    enabled: row.enabled,
                }))
            }
        }
    }
}

// --- Internal types (raw rows) -----------------------------------------------

/// Raw `trigger_history` row as read from SQLite.
struct RawHistoryRow {
    id: String,
    trigger_id: String,
    agent_name: String,
    fired_at: String,
    task_id: Option<String>,
    status: String,
    reason: Option<String>,
    payload_json: Option<String>,
    dispatch_ms: Option<i64>,
}

/// Raw `trigger_history` row aggregated by `load_counters`.
struct RawCounterRow {
    trigger_id: String,
    fire_count: i64,
    skip_count: i64,
    last_fired: Option<String>,
}

/// Raw `trigger_state` row as read from SQLite.
struct RawStateRow {
    trigger_id: String,
    last_fired: Option<String>,
    fire_count: i64,
    skip_count: i64,
    enabled: bool,
}

