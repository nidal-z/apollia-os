    #[test]
    fn test_load_counters_mixed_triggers() {
        // GIVEN two triggers with different histories
        let (_dir, mut persistence) = open_test_db();
        let now = Utc::now();
        // trigger-a: 5 fires, 1 skip
        for i in 0..5u64 {
            persistence
                .record_fired(
                    TriggerRecord {
                        trigger_id: "trigger-a",
                        agent_name: "agent",
                        fired_at: now + chrono::Duration::seconds(i as i64),
                        payload_json: None,
                    },
                    &format!("t{i}"),
                    None,
                )
                .unwrap();
        }
        persistence
            .record_skipped(
                TriggerRecord {
                    trigger_id: "trigger-a",
                    agent_name: "agent",
                    fired_at: now,
                    payload_json: None,
                },
                "busy",
            )
            .unwrap();
        // trigger-b: 0 fires, 3 skips
        for _ in 0..3 {
            persistence
                .record_skipped(
                    TriggerRecord {
                        trigger_id: "trigger-b",
                        agent_name: "agent",
                        fired_at: now,
                        payload_json: None,
                    },
                    "busy",
                )
                .unwrap();
        }
        // WHEN
        let counters = persistence.load_counters().unwrap();
        // THEN independent counters
        let a = counters.get("trigger-a").expect("trigger-a absent");
        assert_eq!(a.fire_count, 5);
        assert_eq!(a.skip_count, 1);
        let b = counters.get("trigger-b").expect("trigger-b absent");
        assert_eq!(b.fire_count, 0);
        assert_eq!(b.skip_count, 3);
    }

