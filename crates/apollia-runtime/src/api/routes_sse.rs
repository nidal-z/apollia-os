    #[tokio::test]
    async fn test_take_while_inclusive_includes_terminal() {
        // GIVEN a stream of numbers
        let items = vec![1, 2, 3, 4, 5];
        let stream = tokio_stream::iter(items);

        // WHEN applying take_while_inclusive with predicate < 4
        let collected: Vec<i32> = stream.take_while_inclusive(|x| *x < 4).collect().await;

        // THEN we get [1, 2, 3, 4] (4 included, the first item that fails the predicate)
        assert_eq!(collected, vec![1, 2, 3, 4]);
    }

