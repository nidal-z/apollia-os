/// SSE event sent to the client.
///
/// Serialized as a flat JSON object with an `event` field discriminating
/// the event type and additional data fields depending on the variant.
#[derive(Debug, Serialize)]
pub struct SseTaskEvent {
    /// Event type: "step", "tool_call", "completed", "failed", "canceled", "started".
    pub event: String,
    /// Additional event data (flattened into the top-level JSON object).
    #[serde(flatten)]
    pub data: serde_json::Value,
}

/// Standard error response body (same as routes_tasks).
#[derive(Debug, Serialize)]
struct ErrorResponse {
    /// Human-readable error description.
    error: String,
}

/// Convert a [`RuntimeEvent`] into an [`SseTaskEvent`] if it matches the given `task_id`.
///
/// Returns `None` for events that do not belong to the task or are not relevant
/// for per-task streaming (e.g. system-level events).
/// Returns `Some((event, is_terminal))`, `is_terminal` is true for events that
/// signal the end of the task execution (completed, failed, canceled, plan_failed).
fn runtime_event_to_sse(event: &RuntimeEvent, task_id: &str) -> Option<(SseTaskEvent, bool)> {
    match event {
        // Direct-mode events
        RuntimeEvent::StepExecuted {
            task_id: tid,
            step,
            tool,
        } if tid == task_id => {
            let data = match tool {
                Some(t) => serde_json::json!({ "step": step, "tool": t }),
                None => serde_json::json!({ "step": step }),
            };
            Some((
                SseTaskEvent {
                    event: "step".into(),
                    data,
                },
                false,
            ))
        }
        RuntimeEvent::TaskStarted {
            task_id: tid,
            agent_id,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "started".into(),
                data: serde_json::json!({ "agent_id": agent_id }),
            },
            false,
        )),
        RuntimeEvent::TaskCompleted {
            task_id: tid,
            success,
            output,
            ..
        } if tid == task_id => {
            let event_name = if *success { "completed" } else { "failed" };
            // Include the agent output text in the "completed" event so that CLI
            // callers (both polling and SSE) can display the result without a
            // separate endpoint (GET /api/v1/tasks/:id never carries the output).
            //
            // For failures we surface the same text under `error` so the CLI
            // can render an actionable message instead of falling back to a
            // generic "unknown error". The coordinator already encodes
            // `[CODE] message details=…` in `output` on failure, so this
            // re-surfaces the worker-reported reason all the way to the
            // operator.
            let mut data = serde_json::json!({ "success": success });
            if let Some(text) = output {
                if *success {
                    data["result"] = serde_json::Value::String(text.clone());
                } else {
                    data["error"] = serde_json::Value::String(text.clone());
                }
            }
            Some((
                SseTaskEvent {
                    event: event_name.into(),
                    data,
                },
                true,
            ))
        }
        RuntimeEvent::TaskCanceled { task_id: tid } if tid == task_id => Some((
            SseTaskEvent {
                event: "canceled".into(),
                data: serde_json::json!({}),
            },
            true,
        )),

        // Orchestrated plan events

        // A new execution plan has been generated by the Reasoner.
        RuntimeEvent::PlanGenerated {
            task_id: tid,
            plan_id,
            step_count,
            agent_name,
            run_id: _,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "plan_generated".into(),
                data: serde_json::json!({
                    "plan_id":    plan_id,
                    "step_count": step_count,
                    "agent_name": agent_name,
                }),
            },
            false,
        )),

        // A plan step has started its execution.
        RuntimeEvent::StepStarted {
            task_id: tid,
            plan_id,
            step_id,
            step_num,
            total,
            desc,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "step_started".into(),
                data: serde_json::json!({
                    "plan_id": plan_id,
                    "step_id": step_id,
                    "num":     step_num,
                    "total":   total,
                    "desc":    desc,
                }),
            },
            false,
        )),

        // A plan step completed successfully.
        RuntimeEvent::StepCompleted {
            task_id: tid,
            plan_id,
            step_id,
            duration_ms,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "step_completed".into(),
                data: serde_json::json!({
                    "plan_id":     plan_id,
                    "step_id":     step_id,
                    "duration_ms": duration_ms,
                }),
            },
            false,
        )),

        // A plan step failed, may trigger replanning.
        RuntimeEvent::StepFailed {
            task_id: tid,
            plan_id,
            step_id,
            error,
            retryable,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "step_failed".into(),
                data: serde_json::json!({
                    "plan_id":   plan_id,
                    "step_id":   step_id,
                    "error":     error,
                    "retryable": retryable,
                }),
            },
            false,
        )),

        // A replanning cycle has been triggered after a retryable step failure.
        RuntimeEvent::PlanReplanning {
            task_id: tid,
            plan_id,
            attempt,
            failed_step,
            reason,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "replanning".into(),
                data: serde_json::json!({
                    "plan_id":     plan_id,
                    "attempt":     attempt,
                    "failed_step": failed_step,
                    "reason":      reason,
                }),
            },
            false,
        )),

        // All steps completed, the plan finished successfully.
        RuntimeEvent::PlanCompleted {
            task_id: tid,
            plan_id,
            step_count,
            duration_ms,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "plan_completed".into(),
                data: serde_json::json!({
                    "plan_id":     plan_id,
                    "step_count":  step_count,
                    "duration_ms": duration_ms,
                }),
            },
            false,
        )),

        // The plan failed irrecoverably, terminal event, closes the stream.
        RuntimeEvent::PlanFailed {
            task_id: tid,
            plan_id,
            reason,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "plan_failed".into(),
                data: serde_json::json!({
                    "plan_id": plan_id,
                    "reason":  reason,
                }),
            },
            true,
        )),

        // Human-in-the-loop events

        // The task is suspended waiting for human approval, non-terminal.
        RuntimeEvent::TaskInputRequired {
            task_id: tid,
            prompt,
            step_id,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "input_required".into(),
                data: serde_json::json!({
                    "task_id":  tid,
                    "prompt":   prompt,
                    "step_id":  step_id,
                    "channel":  "approvals",
                }),
            },
            false,
        )),

        // The task has been resumed after HITL, non-terminal, execution continues.
        RuntimeEvent::TaskResumed {
            task_id: tid,
            approved,
        } if tid == task_id => Some((
            SseTaskEvent {
                event: "resumed".into(),
                data: serde_json::json!({
                    "task_id":  tid,
                    "approved": approved,
                    "channel":  "approvals",
                }),
            },
            false,
        )),

        _ => None,
    }
}

/// Handler for `GET /api/v1/tasks/{id}/stream`.
///
/// Subscribes to the runtime EventBus and streams task-specific events via SSE.
/// Returns 404 if the task does not exist in the TaskRouter.
/// The stream closes after a terminal event (completed/failed/canceled).
/// Client disconnection drops the subscriber automatically (no leak).
pub async fn stream_task<B: ExecutionBackend + Clone>(
    State(state): State<AppState<B>>,
    Path(task_id): Path<String>,
) -> Result<Sse<impl tokio_stream::Stream<Item = Result<Event, Infallible>>>, impl IntoResponse> {
    // Verify the task exists before subscribing
    let status = state
        .router_handle
        .get_status(&task_id)
        .await
        .map_err(|_| {
            (
                StatusCode::INTERNAL_SERVER_ERROR,
                Json(ErrorResponse {
                    error: "router actor is dead".into(),
                }),
            )
        })?;

    if status.is_none() {
        return Err((
            StatusCode::NOT_FOUND,
            Json(ErrorResponse {
                error: format!("task not found: {task_id}"),
            }),
        ));
    }

    // Subscribe to the EventBus broadcast channel
    let rx = state.event_sender.subscribe();
    let stream = BroadcastStream::new(rx);

    // Filter events for this task_id, convert to SSE frames, stop on terminal
    let task_id_owned = task_id.clone();
    let sse_stream = stream
        .filter_map(move |result| {
            match result {
                Ok(event) => runtime_event_to_sse(&event, &task_id_owned),
                // Lagged receiver: skip lost events silently
                Err(_) => None,
            }
        })
        .map(|(sse_event, is_terminal)| (sse_event, is_terminal))
        // Take events until (and including) the first terminal event
        .take_while_inclusive(|(_event, is_terminal)| !is_terminal)
        .map(|(sse_event, _)| {
            let json = serde_json::to_string(&sse_event).unwrap_or_else(|_| "{}".into());
            Ok(Event::default().data(json))
        });

    Ok(Sse::new(sse_stream).keep_alive(KeepAlive::default()))
}

/// Extension trait to add `take_while_inclusive` to streams.
///
/// Unlike `take_while`, this yields the first item that fails the predicate
/// before closing the stream, needed to send the terminal SSE event.
struct TakeWhileInclusive<S, F> {
    stream: S,
    predicate: F,
    done: bool,
}

impl<S, F, T> tokio_stream::Stream for TakeWhileInclusive<S, F>
where
    S: tokio_stream::Stream<Item = T> + Unpin,
    F: FnMut(&T) -> bool + Unpin,
{
    type Item = T;

    fn poll_next(
        self: std::pin::Pin<&mut Self>,
        cx: &mut std::task::Context<'_>,
    ) -> std::task::Poll<Option<Self::Item>> {
        let this = self.get_mut();
        if this.done {
            return std::task::Poll::Ready(None);
        }
        match std::pin::Pin::new(&mut this.stream).poll_next(cx) {
            std::task::Poll::Ready(Some(item)) => {
                if (this.predicate)(&item) {
                    std::task::Poll::Ready(Some(item))
                } else {
                    this.done = true;
                    std::task::Poll::Ready(Some(item))
                }
            }
            std::task::Poll::Ready(None) => std::task::Poll::Ready(None),
            std::task::Poll::Pending => std::task::Poll::Pending,
        }
    }
}

/// Extension trait providing `take_while_inclusive` on any stream.
trait TakeWhileInclusiveExt: tokio_stream::Stream + Sized {
    /// Yields items while `predicate` returns true, then yields the first
    /// item for which `predicate` returns false and closes.
    fn take_while_inclusive<F>(self, predicate: F) -> TakeWhileInclusive<Self, F>
    where
        F: FnMut(&Self::Item) -> bool;
}

impl<S: tokio_stream::Stream> TakeWhileInclusiveExt for S {
    fn take_while_inclusive<F>(self, predicate: F) -> TakeWhileInclusive<Self, F>
    where
        F: FnMut(&Self::Item) -> bool,
    {
        TakeWhileInclusive {
            stream: self,
            predicate,
            done: false,
        }
    }
}

