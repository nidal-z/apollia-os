#!/usr/bin/env python3
"""Pack the documentation site into the archive the desktop application embeds.

The desktop shows the whole documentation offline. It does not ship the built
site: it ships the Markdown sources the site is built from, the images they
reference, the OpenAPI document the HTTP reference is rendered from, and a
manifest that carries what Docusaurus would otherwise compute at build time:
the sidebar tree, the route of each page, its title, its previous and next
pages, the languages it exists in, and its public address. The same sources
serve the site and the application, and nothing produced here is committed:
the desktop build script writes the archive into its own build directory.

The manifest follows the rules of the Docusaurus version this site pins, read
from its own sources (`@docusaurus/plugin-content-docs`): a doc id and route
drop the number prefixes of its path, a folder's `index.md` is the folder's
route and the link of its category, items sort by position and then by file
name, a category takes its position from `_category_.json`, then from its
linked doc, then from its number prefix, and previous and next walk the
flattened tree, categories with a link included. `sidebars.js` is read as text
and only the autogenerated form is accepted: anything else stops the run
rather than producing a tree the site does not show. The same holds for the
front matter keys that would bend the tree (`pagination_prev`, `draft`, and
their kin): a page that uses one stops the run until this script learns it.

Two choices follow the site. A page without a French mirror is listed in
English under the French tree, which is what the site serves on its French
route. The generated references (HTTP API, SDK, CLI) are English only. The HTTP
reference pages themselves are produced at site build time from
`clients/openapi.json`, so the archive carries the OpenAPI document rather than
those pages.

Archive layout:
    manifest.json
    docs/en/<path of the page under docs/>
    docs/fr/<path of the page under docs/>      (French mirrors only)
    img/<path under static/img/>
    openapi.json

The archive is deterministic: entries in sorted order, one fixed timestamp,
deflate at level 9. Two runs on the same tree produce the same bytes.

Exit codes:
  0  the archive was written.
  1  the sources are inconsistent (an unsupported sidebar or front matter key,
     a French mirror with another route, a route served twice).
  2  nothing measured: the site, its docs folder or the OpenAPI document is
     absent.

Usage:
    python3 docs/site/scripts/embed_docs.py --out <archive.zip>
    python3 docs/site/scripts/embed_docs.py --manifest
"""

import argparse
import json
import re
import sys
import zipfile
from dataclasses import dataclass
from pathlib import Path

SITE_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = SITE_DIR.parent.parent

MANIFEST_FORMAT = 1
PUBLIC_URL = "https://docs.apollia.fr"
DEFAULT_LANGUAGE = "en"
LANGUAGES = ("en", "fr")
FR_DOCS = Path("i18n/fr/docusaurus-plugin-content-docs/current")
FR_LABELS = Path("i18n/fr/docusaurus-plugin-content-docs/current.json")
IMAGES = Path("static/img")
OPENAPI = Path("clients/openapi.json")

# Pages produced at site build time from the OpenAPI document, not sources.
EXCLUDED_DIRS = ("reference/api",)
# Pages generated from the code, in English only on the site as well.
GENERATED_PREFIXES = ("reference/api/", "reference/cli/", "reference/sdk/")

DOC_SUFFIXES = (".md", ".mdx")
SUPPORTED_FRONT_MATTER = {
    "id",
    "slug",
    "title",
    "description",
    "sidebar_label",
    "sidebar_position",
    "pagination_label",
    "hide_title",
    "format",
}
# Fixed timestamp of every entry: the zip epoch.
ZIP_EPOCH = (1980, 1, 1, 0, 0, 0)

NUMBER_PREFIX = re.compile(r"^(?P<number>\d+)\s*[-_.]+\s*(?P<suffix>[^-_.\s].*)$")
IGNORED_PREFIX = re.compile(r"^\d+[-_.]\d+")
FRONT_MATTER = re.compile(r"\A---\r?\n(?P<body>.*?)\r?\n---\r?\n", re.DOTALL)
FRONT_MATTER_LINE = re.compile(r"^(?P<key>[A-Za-z_][\w-]*)\s*:\s*(?P<value>.*)$")
HEADING_ONE = re.compile(r"^#\s+(?P<title>.+?)\s*#*\s*$", re.MULTILINE)


class EmbedError(Exception):
    """The sources cannot be packed as they stand."""


@dataclass
class Doc:
    """One page, in one language."""

    source: str  # path under docs/, posix
    dir_name: str  # "." at the root
    doc_id: str
    route: str
    title: str
    position: float | None
    sidebar_label: str | None
    pagination_label: str | None


def parse_number_prefix(name: str) -> tuple[str, int | None]:
    """`08-decisions` gives `("decisions", 8)`, a date-like name is left whole."""
    if IGNORED_PREFIX.match(name):
        return name, None
    match = NUMBER_PREFIX.match(name)
    if match is None:
        return name, None
    return match.group("suffix"), int(match.group("number"))


def strip_dir_prefixes(dir_name: str) -> str:
    return "/".join(parse_number_prefix(part)[0] for part in dir_name.split("/"))


def unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        inner = value[1:-1]
        return inner.replace('\\"', '"') if value[0] == '"' else inner.replace("''", "'")
    return value


def front_matter(text: str, where: str) -> tuple[dict[str, str], str]:
    """The front matter keys of a page, and the content after them."""
    match = FRONT_MATTER.match(text)
    if match is None:
        return {}, text
    keys: dict[str, str] = {}
    for line in match.group("body").splitlines():
        if not line.strip() or line.startswith((" ", "\t", "#")):
            continue
        parsed = FRONT_MATTER_LINE.match(line)
        if parsed is None:
            raise EmbedError(f"{where}: unreadable front matter line {line!r}")
        key = parsed.group("key")
        if key not in SUPPORTED_FRONT_MATTER:
            raise EmbedError(
                f"{where}: front matter key {key!r} is not supported by the embedded "
                "documentation; teach docs/site/scripts/embed_docs.py what the site does with it"
            )
        keys[key] = unquote(parsed.group("value"))
    return keys, text[match.end() :]


def is_category_index(file_stem: str, dir_name: str) -> bool:
    last_dir = dir_name.split("/")[-1].lower() if dir_name != "." else ""
    return file_stem.lower() in ("index", "readme", last_dir)


def normalize_route(route: str) -> str:
    """Collapse doubled slashes; a trailing slash stays, as on the site."""
    return re.sub(r"/+", "/", route)


def resolve_slug(slug: str, dir_route: str) -> str:
    """A relative front matter slug resolves against the folder route."""
    parts = [p for p in dir_route.split("/") if p]
    for part in slug.split("/"):
        if part in ("", "."):
            continue
        if part == "..":
            if parts:
                parts.pop()
            continue
        parts.append(part)
    return "/" + "/".join(parts)


def read_doc(path: Path, source: str, where: str) -> Doc:
    text = path.read_text(encoding="utf-8")
    keys, content = front_matter(text, where)
    dir_name = str(Path(source).parent.as_posix())
    stem = Path(source).stem
    unprefixed, number = parse_number_prefix(stem)
    base_id = keys.get("id", unprefixed)
    if "/" in base_id:
        raise EmbedError(f"{where}: a doc id cannot hold a slash")
    stripped_dir = strip_dir_prefixes(dir_name) if dir_name != "." else ""
    doc_id = f"{stripped_dir}/{base_id}" if stripped_dir else base_id
    dir_route = "/" if dir_name == "." else f"/{stripped_dir}/"
    slug = keys.get("slug")
    if slug is not None and slug.startswith("/"):
        route = slug
    elif slug is None and is_category_index(stem, dir_name):
        route = dir_route
    else:
        route = resolve_slug(slug if slug is not None else base_id, dir_route)
    heading = HEADING_ONE.search(content)
    title = keys.get("title") or (heading.group("title") if heading else None) or base_id
    position_text = keys.get("sidebar_position")
    try:
        position = float(position_text) if position_text is not None else number
    except ValueError as error:
        raise EmbedError(f"{where}: sidebar_position {position_text!r} is not a number") from error
    return Doc(
        source=source,
        dir_name=dir_name,
        doc_id=doc_id,
        route=normalize_route(route),
        title=title,
        position=position,
        sidebar_label=keys.get("sidebar_label"),
        pagination_label=keys.get("pagination_label"),
    )


def check_sidebars(site: Path) -> str:
    """The folder `sidebars.js` autogenerates, or a refusal of any other form."""
    path = site / "sidebars.js"
    if not path.is_file():
        raise EmbedError("docs/site/sidebars.js is absent")
    text = path.read_text(encoding="utf-8")
    code = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    code = re.sub(r"(?m)^\s*//.*$", "", code)
    sidebars = re.findall(r"(\w+)\s*:\s*\[", code)
    items = re.findall(r"\{\s*type\s*:\s*'(\w+)'\s*,\s*dirName\s*:\s*'([^']*)'\s*\}", code)
    types = re.findall(r"type\s*:\s*'(\w+)'", code)
    if sidebars != ["docs"] or len(items) != 1 or types != ["autogenerated"]:
        raise EmbedError(
            "docs/site/sidebars.js is not the single autogenerated sidebar this script reads; "
            "teach docs/site/scripts/embed_docs.py the new form"
        )
    return items[0][1]


def doc_files(root: Path) -> list[str]:
    """Pages under `root`, posix paths, without the `_` files Docusaurus skips."""
    found = []
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.suffix not in DOC_SUFFIXES:
            continue
        rel = path.relative_to(root).as_posix()
        if any(part.startswith("_") for part in rel.split("/")):
            continue
        if any(rel == d or rel.startswith(d + "/") for d in EXCLUDED_DIRS):
            continue
        found.append(rel)
    return found


def category_metadata(docs_root: Path, folder: str) -> dict:
    path = docs_root / folder / "_category_.json"
    if path.is_file():
        return json.loads(path.read_text(encoding="utf-8"))
    for name in ("_category_.yml", "_category_.yaml"):
        if (docs_root / folder / name).is_file():
            raise EmbedError(f"{folder}/{name}: only _category_.json is read")
    return {}


def sort_key(item) -> tuple:
    position = item[0]
    return (position is None, position if position is not None else 0.0, item[1])


def build_tree(docs: dict[str, Doc], docs_root: Path) -> list:
    """The sidebar items, in Docusaurus order, as nested dicts."""
    root: dict = {}
    for source, doc in docs.items():
        node = root
        if doc.dir_name != ".":
            for part in doc.dir_name.split("/"):
                node = node.setdefault(part, {})
        node[Path(source).name] = doc

    def doc_label(doc: Doc) -> str:
        return doc.sidebar_label or doc.title

    def to_items(node: dict, folder: str) -> list:
        raw = []
        for key, content in node.items():
            path = f"{folder}/{key}" if folder else key
            if isinstance(content, Doc):
                raw.append((content.position, key, {"kind": "doc", "doc": content}))
                continue
            children = to_items(content, path)
            meta = category_metadata(docs_root, path)
            link = meta.get("link")
            linked: Doc | None = None
            link_route = None
            if link is not None and link.get("type") != "doc":
                if link.get("type") != "generated-index" or not link.get("slug"):
                    raise EmbedError(f"{path}/_category_.json: a category link needs type and slug")
                link_route = normalize_route(link["slug"])
            else:
                candidates = [c for c in children if c["kind"] == "doc"]
                if link is not None:
                    wanted = link.get("id", "")
                    linked = next(
                        (c["doc"] for c in candidates if c["doc"].doc_id.split("/")[-1] == wanted or c["doc"].doc_id == wanted),
                        None,
                    )
                    if linked is None:
                        raise EmbedError(f"{path}/_category_.json: linked doc {wanted!r} not found")
                else:
                    linked = next(
                        (
                            c["doc"]
                            for c in candidates
                            if is_category_index(Path(c["doc"].source).stem, c["doc"].dir_name)
                        ),
                        None,
                    )
                if linked is not None:
                    link_route = linked.route
                    children = [c for c in children if not (c["kind"] == "doc" and c["doc"] is linked)]
            unprefixed, number = parse_number_prefix(key)
            label = meta.get("label") or (doc_label(linked) if linked else None) or unprefixed
            position = meta.get("position")
            if position is None:
                position = linked.position if linked else number
            category = {
                "kind": "category",
                "label": label,
                "link": link_route,
                "link_doc": linked,
                "items": children,
            }
            raw.append((position, key, category))
        raw.sort(key=sort_key)
        return [item for _, _, item in raw]

    return to_items(root, "")


def flatten(items: list) -> list:
    out = []
    for item in items:
        out.append(item)
        if item["kind"] == "category":
            out.extend(flatten(item["items"]))
    return out


def render_tree(items: list, labels: dict[str, str]) -> list:
    rendered = []
    for item in items:
        if item["kind"] == "doc":
            doc = item["doc"]
            rendered.append({"kind": "doc", "route": doc.route, "label": doc.sidebar_label or doc.title})
        else:
            rendered.append(
                {
                    "kind": "category",
                    "label": labels.get(item["label"], item["label"]),
                    "route": item["link"],
                    "items": render_tree(item["items"], labels),
                }
            )
    return rendered


def navigation(items: list, labels: dict[str, str]) -> dict[str, dict]:
    """Title, previous and next of every route the sidebar can open."""
    stops = []
    for item in flatten(items):
        if item["kind"] == "doc":
            doc = item["doc"]
            title = doc.pagination_label or doc.sidebar_label or doc.title
            stops.append((doc.route, title, "page"))
        elif item["link"] is not None:
            linked = item["link_doc"]
            if linked is not None:
                title = linked.pagination_label or linked.sidebar_label or linked.title
                stops.append((linked.route, title, "page"))
            else:
                stops.append((item["link"], labels.get(item["label"], item["label"]), "generated-index"))
    entries: dict[str, dict] = {}
    for index, (route, title, kind) in enumerate(stops):
        if route in entries:
            raise EmbedError(f"route {route} is reached twice by the sidebar")
        previous = stops[index - 1] if index > 0 else None
        following = stops[index + 1] if index + 1 < len(stops) else None
        entries[route] = {
            "kind": kind,
            "title": title,
            "previous": {"route": previous[0], "title": previous[1]} if previous else None,
            "next": {"route": following[0], "title": following[1]} if following else None,
        }
    return entries


def read_language(site: Path, sources: list[str], language: str) -> tuple[dict[str, Doc], set[str]]:
    """Every page in `language`, falling back to English where no mirror exists."""
    en_root = site / "docs"
    fr_root = site / FR_DOCS
    docs: dict[str, Doc] = {}
    mirrored: set[str] = set()
    for source in sources:
        path = en_root / source
        if language == "fr" and (fr_root / source).is_file():
            path = fr_root / source
            mirrored.add(source)
        where = path.relative_to(site).as_posix()
        docs[source] = read_doc(path, source, where)
    return docs, mirrored


def build(site: Path, openapi: Path) -> tuple[dict, list[tuple[str, bytes]]]:
    """The manifest and the archive entries, in archive order."""
    docs_root = site / "docs"
    if not docs_root.is_dir():
        raise FileNotFoundError(f"{docs_root} is absent")
    if not openapi.is_file():
        raise FileNotFoundError(f"{openapi} is absent")
    autogen_dir = check_sidebars(site)
    if autogen_dir != ".":
        raise EmbedError("sidebars.js autogenerates a subfolder; only '.' is read")
    sources = doc_files(docs_root)
    if not sources:
        raise FileNotFoundError(f"{docs_root} holds no page")

    labels_path = site / FR_LABELS
    fr_labels: dict[str, str] = {}
    if labels_path.is_file():
        for key, value in json.loads(labels_path.read_text(encoding="utf-8")).items():
            prefix = "sidebar.docs.category."
            if key.startswith(prefix) and not key.endswith((".link.generated-index.title", ".link.generated-index.description")):
                fr_labels[key[len(prefix) :]] = value["message"]

    pages: dict[str, dict] = {}
    locales: dict[str, dict] = {}
    entries: list[tuple[str, bytes]] = []
    by_language: dict[str, dict[str, Doc]] = {}
    mirrored: set[str] = set()
    for language in LANGUAGES:
        docs, mirrored_here = read_language(site, sources, language)
        by_language[language] = docs
        if language == "fr":
            mirrored = mirrored_here
        labels = fr_labels if language == "fr" else {}
        tree = build_tree(docs, docs_root)
        prefix = "" if language == DEFAULT_LANGUAGE else f"/{language}"
        locales[language] = {
            "public_url": f"{PUBLIC_URL}{prefix}",
            "tree": render_tree(tree, labels),
            "navigation": navigation(tree, labels),
        }

    seen_routes: dict[str, str] = {}
    for source in sources:
        en_doc = by_language["en"][source]
        fr_doc = by_language["fr"][source]
        if fr_doc.route != en_doc.route:
            raise EmbedError(
                f"{source}: the French mirror is served at {fr_doc.route}, the English page at "
                f"{en_doc.route}; both locales must serve the same route"
            )
        if en_doc.route in seen_routes:
            raise EmbedError(f"{source} and {seen_routes[en_doc.route]} both serve {en_doc.route}")
        seen_routes[en_doc.route] = source
        languages = ["en", "fr"] if source in mirrored else ["en"]
        pages[en_doc.route] = {
            "source": source,
            "languages": languages,
            "generated": source.startswith(GENERATED_PREFIXES),
        }
        entries.append((f"docs/en/{source}", (docs_root / source).read_bytes()))
        if source in mirrored:
            entries.append((f"docs/fr/{source}", (site / FR_DOCS / source).read_bytes()))

    images = site / IMAGES
    if images.is_dir():
        for path in sorted(images.rglob("*")):
            if path.is_file() and not path.name.startswith("."):
                entries.append((f"img/{path.relative_to(images).as_posix()}", path.read_bytes()))
    entries.append(("openapi.json", openapi.read_bytes()))

    manifest = {
        "format": MANIFEST_FORMAT,
        "public_url": PUBLIC_URL,
        "default_language": DEFAULT_LANGUAGE,
        "languages": list(LANGUAGES),
        "openapi": "openapi.json",
        "pages": pages,
        "locales": locales,
    }
    manifest_bytes = (json.dumps(manifest, ensure_ascii=False, indent=1, sort_keys=True) + "\n").encode("utf-8")
    entries = [("manifest.json", manifest_bytes)] + sorted(entries)
    return manifest, entries


def write_archive(entries: list[tuple[str, bytes]], out: Path) -> int:
    """Write the archive deterministically; returns its size in bytes."""
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_name(out.name + ".partial")
    with zipfile.ZipFile(tmp, "w") as archive:
        for name, data in entries:
            info = zipfile.ZipInfo(name, date_time=ZIP_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, data, compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    tmp.replace(out)
    return out.stat().st_size


def main() -> int:
    parser = argparse.ArgumentParser(description="Pack the documentation site for the desktop application.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--out", type=Path, help="path of the archive to write")
    group.add_argument("--manifest", action="store_true", help="print the manifest and write nothing")
    parser.add_argument("--site", type=Path, default=SITE_DIR, help="the documentation site (default: this one)")
    parser.add_argument("--openapi", type=Path, default=REPO_ROOT / OPENAPI, help="the OpenAPI document")
    args = parser.parse_args()
    try:
        manifest, entries = build(args.site, args.openapi)
    except FileNotFoundError as error:
        print(f"embed_docs: nothing to pack: {error}", file=sys.stderr)  # REASON: print-call: command-line entry point
        return 2
    except EmbedError as error:
        print(f"embed_docs: {error}", file=sys.stderr)  # REASON: print-call: command-line entry point
        return 1
    if args.manifest:
        print(json.dumps(manifest, ensure_ascii=False, indent=1, sort_keys=True))  # REASON: print-call: command-line entry point
        return 0
    size = write_archive(entries, args.out)
    counts = {lang: sum(1 for p in manifest["pages"].values() if lang in p["languages"]) for lang in LANGUAGES}
    print(  # REASON: print-call: command-line entry point
        f"embed_docs: {len(manifest['pages'])} pages ({counts['en']} en, {counts['fr']} fr), "
        f"{len(entries)} entries, {size} bytes compressed"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
