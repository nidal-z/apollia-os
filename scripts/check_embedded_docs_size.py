#!/usr/bin/env python3
"""Hold the documentation the desktop embeds under its size ceiling.

The desktop application carries the whole documentation site, offline: the
Markdown sources, the images they show, the OpenAPI document and a manifest,
packed into one compressed archive by `docs/site/scripts/embed_docs.py` and
included in the binary at build time. Every byte of that archive is a byte of
the installer, and nothing in the build notices when a page gains a dozen full
screen captures. This guard packs the archive the way the build does, prints
its compressed size, and refuses it past the ceiling.

The ceiling is 20 MB compressed (20 000 000 bytes). The measure is the
compressed size because that is what ships: a large text file that deflates
well costs little, a PNG that does not deflate costs its whole weight.

Exit codes:
  0  the archive fits under the ceiling.
  1  the archive is over the ceiling, or the sources cannot be packed.
  2  nothing measured: the documentation site or the OpenAPI document is
     absent.

Usage:
    python3 scripts/check_embedded_docs_size.py
    python3 scripts/check_embedded_docs_size.py --selftest
"""

import argparse
import importlib.util
import os
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SITE_DIR = REPO_ROOT / "docs/site"
OPENAPI = REPO_ROOT / "clients/openapi.json"
EMBED_SCRIPT = SITE_DIR / "scripts/embed_docs.py"

CEILING_BYTES = 20_000_000


def load_embed():
    """The packing module the desktop build script runs."""
    spec = importlib.util.spec_from_file_location("embed_docs", EMBED_SCRIPT)
    if spec is None or spec.loader is None:
        raise FileNotFoundError(f"{EMBED_SCRIPT} is absent")
    module = importlib.util.module_from_spec(spec)
    sys.modules["embed_docs"] = module
    spec.loader.exec_module(module)
    return module


def measure(site: Path, openapi: Path, ceiling: int) -> tuple[int, list[str]]:
    """Exit code and report lines for the archive packed from `site`."""
    if not EMBED_SCRIPT.is_file():
        return 2, [f"check_embedded_docs_size: {EMBED_SCRIPT.relative_to(REPO_ROOT)} is absent, nothing measured"]
    embed = load_embed()
    try:
        manifest, entries = embed.build(site, openapi)
    except FileNotFoundError as error:
        return 2, [f"check_embedded_docs_size: nothing measured: {error}"]
    except embed.EmbedError as error:
        return 1, [f"check_embedded_docs_size: the sources cannot be packed: {error}"]
    with tempfile.TemporaryDirectory() as tmp:
        size = embed.write_archive(entries, Path(tmp) / "docs.zip")
    raw = sum(len(data) for _, data in entries)
    line = (
        f"check_embedded_docs_size: {len(manifest['pages'])} pages, {len(entries)} entries, "
        f"{raw} bytes raw, {size} bytes compressed ({size / 1_000_000:.2f} MB), ceiling {ceiling} bytes"
    )
    if size > ceiling:
        return 1, [
            line,
            f"  over: the archive exceeds the ceiling by {size - ceiling} bytes; "
            "shrink the images or decide a new ceiling in this file",
        ]
    return 0, [line, "check_embedded_docs_size: the embedded documentation fits"]


# ── selftest ─────────────────────────────────────────────────────────────────


def _site(root: Path, image_bytes: bytes) -> tuple[Path, Path]:
    site = root / "site"
    (site / "docs/guide").mkdir(parents=True)
    (site / "static/img").mkdir(parents=True)
    (site / "sidebars.js").write_text(
        "const sidebars = {\n  docs: [{ type: 'autogenerated', dirName: '.' }],\n};\n"
        "module.exports = sidebars;\n",
        encoding="utf-8",
    )
    (site / "docs/intro.md").write_text("---\nslug: /\ntitle: Home\n---\n\nHello.\n", encoding="utf-8")
    (site / "docs/guide/index.md").write_text("# Guide\n\n" + "words " * 5000, encoding="utf-8")
    (site / "static/img/shot.png").write_bytes(image_bytes)
    openapi = root / "openapi.json"
    openapi.write_text('{"openapi": "3.1.0"}\n', encoding="utf-8")
    return site, openapi


def selftest() -> int:
    cases: list[tuple[str, bool]] = []
    incompressible = os.urandom(200_000)

    def run(image: bytes, ceiling: int, break_sidebar: bool = False, drop_docs: bool = False) -> tuple[int, str]:
        with tempfile.TemporaryDirectory() as tmp:
            site, openapi = _site(Path(tmp), image)
            if break_sidebar:
                (site / "sidebars.js").write_text("module.exports = { docs: ['intro'] };\n", encoding="utf-8")
            if drop_docs:
                for path in sorted((site / "docs").rglob("*"), reverse=True):
                    path.unlink() if path.is_file() else path.rmdir()
                (site / "docs").rmdir()
            code, lines = measure(site, openapi, ceiling)
            return code, "\n".join(lines)

    code, text = run(b"png", 1_000_000)
    cases.append(("a small archive passes and prints its compressed size", code == 0 and "bytes compressed" in text))
    code, text = run(incompressible, 150_000)
    cases.append(("an image that does not deflate pushes the archive over", code == 1 and "over:" in text))
    code, _ = run(b"\0" * 2_000_000, 150_000)
    cases.append(("the ceiling reads the compressed size, not the raw one", code == 0))
    code, _ = run(b"png", 1_000_000, break_sidebar=True)
    cases.append(("a sidebar the packer cannot read is a red", code == 1))
    code, _ = run(b"png", 1_000_000, drop_docs=True)
    cases.append(("a site without docs measures nothing", code == 2))

    failed = [name for name, held in cases if not held]
    for name in failed:
        print(f"selftest FAILED: {name}")
    if failed:
        return 1
    print(f"check_embedded_docs_size --selftest: {len(cases)} assertions, every one holds")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Hold the embedded documentation archive under its size ceiling.")
    parser.add_argument("--selftest", action="store_true", help="check the guard against fixtures")
    args = parser.parse_args()
    if args.selftest:
        return selftest()
    code, lines = measure(SITE_DIR, OPENAPI, CEILING_BYTES)
    for line in lines:
        print(line)
    return code


if __name__ == "__main__":
    sys.exit(main())
